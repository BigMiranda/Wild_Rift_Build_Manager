/** Translates a key, replacing {placeholders}. Falls back to pt, then to the key itself. */
export function t(key, vars) {
  const dict = state.lang === 'en' ? EN : PT;
  let s = dict[key] ?? PT[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

/** Human text of a shop-rule violation returned by the engine. */
export function violationText(v) {
  return t(`rule.${v.code}`, { items: (v.items ?? []).join(', '), group: v.group ? t(`group.${v.group}`) : '' });
}
