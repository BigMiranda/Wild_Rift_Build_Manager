/**
 * Minimal i18n: the language lives in module state, set by App before each render, so plain functions (t, statLabel,
 * statAbbr) can be used anywhere without threading a context. App re-renders the whole tree when it changes.
 * Item names and passive texts come from the pt-BR shop and are not translated.
 */
const STORAGE_KEY = 'ornn-planner-settings';

let state = { lang: 'pt', abbr: 'pt' };

export function loadSettings() {
  try {
    const saved = JSON.parse(localStorage.getItem(STORAGE_KEY) ?? 'null');
    if (saved && (saved.lang === 'pt' || saved.lang === 'en')) return { lang: saved.lang, abbr: saved.abbr === 'en' ? 'en' : 'pt' };
  } catch {
    /* storage unavailable: defaults */
  }
  return { lang: 'pt', abbr: 'pt' };
}

export function saveSettings(s) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(s));
  } catch {
    /* ignore */
  }
}

export function setLanguage(s) {
  state = s;
}

export const currentLang = () => state.lang;

